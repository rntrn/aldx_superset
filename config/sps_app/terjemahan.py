DAFTAR = CANGKANG + STUDIO + KUERI + ASISTEN + PUSAT + TAHAP2 + TAHAP3
FOLDER = Path(__file__).resolve().parent / "static" / "bahasa"


def rapat(teks: str) -> str:
    return re.sub(r"\s+", " ", teks).strip()


def _tulis(nama: str, baris: list, pola: list, kolom: int) -> int:
    """Kunci ganda: baris pertama yang menang."""
    kamus: dict = {}
    for b in baris:
        kamus.setdefault(rapat(b[0]), b[kolom])
    kamus["_pola"] = [[p[0], p[kolom]] for p in pola]
    (FOLDER / f"{nama}.json").write_text(json.dumps(kamus, ensure_ascii=False, indent=0), encoding="utf-8")
    return len(kamus) - 1


def buat() -> dict[str, int]:
    """Tulis static/bahasa/en.json, ja.json, superset-id.json."""
    FOLDER.mkdir(parents=True, exist_ok=True)
    return {"en": _tulis("en", DAFTAR, POLA, 1), "ja": _tulis("ja", DAFTAR, POLA, 2),
            "superset-id": _tulis("superset-id", SUPERSET, POLA_SUPERSET, 1)}


if __name__ == "__main__":
    print(buat())
